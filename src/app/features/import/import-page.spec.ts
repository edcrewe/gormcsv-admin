import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { InspectResult } from '../../../shared/api-types';
import { ImportPage } from './import-page';
import { expectNoAxeViolations } from '../../../testing/axe';

const RESULT: InspectResult = {
  file: 'TestTypes.csv',
  models: [
    {
      name: 'TestTypes',
      key: 'testtypes',
      fields: [
        { name: 'Wordcol', type: 'string' },
        { name: 'Intcol', type: 'int16' },
      ],
    },
  ],
  source: '// Generated by gormcsv.\ntype TestTypes struct {}\n',
  warnings: [],
};

describe('ImportPage', () => {
  let httpTesting: HttpTestingController;

  beforeEach(() => {
    TestBed.configureTestingModule({
      imports: [ImportPage],
      providers: [provideHttpClient(), provideHttpClientTesting()],
    });
    httpTesting = TestBed.inject(HttpTestingController);
  });

  afterEach(() => httpTesting.verify());

  async function render() {
    const fixture = TestBed.createComponent(ImportPage);
    await fixture.whenStable();
    const el = fixture.nativeElement as HTMLElement;
    const button = (label: string) =>
      Array.from(el.querySelectorAll('button')).find((b) => b.textContent?.includes(label))!;

    // jsdom has no DataTransfer, so stand in a FileList on the input and fire change.
    const choose = async (name = 'TestTypes.csv') => {
      const input = el.querySelector<HTMLInputElement>('input[type="file"]')!;
      const file = new File(['a,b\n'], name, { type: 'text/csv' });
      Object.defineProperty(input, 'files', {
        configurable: true,
        value: { 0: file, length: 1, item: () => file },
      });
      input.dispatchEvent(new Event('change'));
      await fixture.whenStable();
      return file;
    };
    const inspect = async () => {
      button('Inspect').click();
      await fixture.whenStable();
    };
    return { fixture, el, button, choose, inspect };
  }

  it('starts with no file selected and Inspect disabled', async () => {
    const { el, button } = await render();

    expect(el.querySelector('.file-name')?.textContent).toContain('No file selected');
    expect(button('Inspect').disabled).toBe(true);
  });

  it('opens the native file picker from the Choose button', async () => {
    const { el, button } = await render();
    const input = el.querySelector<HTMLInputElement>('input[type="file"]')!;
    const click = vi.spyOn(input, 'click');

    button('Choose CSV file').click();

    expect(click).toHaveBeenCalled();
    expect(input.getAttribute('accept')).toBe('.csv,text/csv');
  });

  it('shows the chosen file and enables Inspect', async () => {
    const { el, button, choose } = await render();

    await choose('order-item.csv');

    expect(el.querySelector('.file-name')?.textContent).toContain('order-item.csv');
    expect(button('Inspect').disabled).toBe(false);
  });

  it('uploads the file, shows progress, then the fields and source, and focuses the result', async () => {
    const { fixture, el, button, choose, inspect } = await render();
    await choose();

    await inspect();
    const req = httpTesting.expectOne('/api/inspect');
    expect((req.request.body as FormData).get('file')).toBeInstanceOf(File);
    expect(el.querySelector('mat-progress-bar')).not.toBeNull();
    expect(button('Inspect').disabled).toBe(true);
    expect(button('Choose CSV file').disabled).toBe(true);

    req.flush(RESULT);
    await fixture.whenStable();

    expect(el.querySelector('mat-progress-bar')).toBeNull();
    const heading = el.querySelector<HTMLElement>('#results-heading')!;
    expect(heading.textContent).toContain('Generated model from TestTypes.csv');
    expect(document.activeElement).toBe(heading);
    expect(el.querySelectorAll('app-model-fields-table tbody tr')).toHaveLength(2);
    expect(el.querySelector('app-code-panel pre')?.textContent).toBe(RESULT.source);
  });

  it('shows no warnings box when there are none', async () => {
    const { fixture, el, choose, inspect } = await render();
    await choose();
    await inspect();
    httpTesting.expectOne('/api/inspect').flush(RESULT);
    await fixture.whenStable();

    expect(el.querySelector('.warnings')).toBeNull();
  });

  it('lists CLI warnings above the model', async () => {
    const { fixture, el, choose, inspect } = await render();
    await choose('Country.csv');
    await inspect();
    const warnings = [
      'Country.csv: skipped 1 row with the wrong number of fields (line 148)',
      'Country.csv: another warning',
    ];
    httpTesting.expectOne('/api/inspect').flush({ ...RESULT, file: 'Country.csv', warnings });
    await fixture.whenStable();

    const box = el.querySelector('.results .warnings')!;
    expect(box.querySelector('h4')?.textContent).toContain('2 warnings');
    expect(Array.from(box.querySelectorAll('li')).map((li) => li.textContent?.trim())).toEqual(
      warnings,
    );
    // Warnings come before the fields table, so they are read first after focus moves to the heading.
    const table = el.querySelector('app-model-fields-table')!;
    expect(box.compareDocumentPosition(table) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    await expectNoAxeViolations(el);
  });

  it('shows the server error in an alert and keeps the file for a retry', async () => {
    const { fixture, el, button, choose, inspect } = await render();
    await choose();
    await inspect();

    httpTesting
      .expectOne('/api/inspect')
      .flush(
        { ok: false, error: 'inspect "TestTypes.csv": wrong number of fields' },
        { status: 422, statusText: 'Unprocessable' },
      );
    await fixture.whenStable();

    expect(el.querySelector('[role="alert"]')?.textContent).toContain('wrong number of fields');
    expect(el.querySelector('#results-heading')).toBeNull();
    expect(button('Inspect').disabled).toBe(false);
  });

  it('clears a previous result when a new file is chosen', async () => {
    const { fixture, el, choose, inspect } = await render();
    await choose();
    await inspect();
    httpTesting.expectOne('/api/inspect').flush(RESULT);
    await fixture.whenStable();

    await choose('other.csv');

    expect(el.querySelector('#results-heading')).toBeNull();
    expect(el.querySelector('.file-name')?.textContent).toContain('other.csv');
  });

  it('passes AXE with results shown', async () => {
    const { fixture, el, choose, inspect } = await render();
    await choose();
    await inspect();
    httpTesting.expectOne('/api/inspect').flush(RESULT);
    await fixture.whenStable();

    await expectNoAxeViolations(el);
  });
});
